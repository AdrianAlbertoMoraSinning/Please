-- Keep existing availability behavior but add safe technical history.
create or replace function public.provider_portal_availability_action(
  p_actor uuid,
  p_action text,
  p_payload jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_provider_id uuid;
  v_action text := upper(trim(coalesce(p_action,'')));
  v_item jsonb;
  v_exception_id bigint;
begin
  v_provider_id := public.require_active_provider_user(p_actor);

  if v_action='SAVE_WEEKLY' then
    delete from public.provider_availability where provider_id=v_provider_id;
    for v_item in select value from jsonb_array_elements(coalesce(p_payload->'availability','[]'::jsonb)) loop
      if coalesce((v_item->>'active')::boolean,true) then
        if (v_item->>'weekday')::int not between 1 and 7 then raise exception 'Invalid weekday'; end if;
        if (v_item->>'start_time')::time >= (v_item->>'end_time')::time then raise exception 'Availability end time must be after start time'; end if;
        insert into public.provider_availability(provider_id,weekday,start_time,end_time,active)
        values(v_provider_id,(v_item->>'weekday')::smallint,(v_item->>'start_time')::time,(v_item->>'end_time')::time,true);
      end if;
    end loop;
    insert into public.provider_technical_history(provider_id,event_type,event_label,actor_type,actor_provider_user_id)
    values(v_provider_id,'AVAILABILITY_UPDATED','Weekly service hours updated','PROVIDER',p_actor);
    return jsonb_build_object('ok',true);

  elsif v_action='ADD_EXCEPTION' then
    if nullif(p_payload->>'exception_date','') is null then raise exception 'Date is required'; end if;
    if coalesce(p_payload->>'exception_type','') not in ('AVAILABLE','UNAVAILABLE') then raise exception 'Invalid exception type'; end if;
    insert into public.provider_availability_exceptions(provider_id,exception_date,start_time,end_time,exception_type,reason)
    values(v_provider_id,(p_payload->>'exception_date')::date,nullif(p_payload->>'start_time','')::time,
           nullif(p_payload->>'end_time','')::time,p_payload->>'exception_type',nullif(trim(p_payload->>'reason'),''))
    returning id into v_exception_id;
    insert into public.provider_technical_history(provider_id,event_type,event_label,details,actor_type,actor_provider_user_id)
    values(v_provider_id,'AVAILABILITY_EXCEPTION_ADDED','Availability exception added',jsonb_build_object('exception_id',v_exception_id,'date',p_payload->>'exception_date'),'PROVIDER',p_actor);
    return jsonb_build_object('ok',true,'exception_id',v_exception_id);

  elsif v_action='DELETE_EXCEPTION' then
    v_exception_id := nullif(p_payload->>'exception_id','')::bigint;
    if v_exception_id is null then raise exception 'Exception ID is required'; end if;
    delete from public.provider_availability_exceptions where id=v_exception_id and provider_id=v_provider_id;
    if not found then raise exception 'Availability exception not found'; end if;
    insert into public.provider_technical_history(provider_id,event_type,event_label,details,actor_type,actor_provider_user_id)
    values(v_provider_id,'AVAILABILITY_EXCEPTION_REMOVED','Availability exception removed',jsonb_build_object('exception_id',v_exception_id),'PROVIDER',p_actor);
    return jsonb_build_object('ok',true);
  end if;
  raise exception 'Unsupported availability action';
end;
$$;
revoke all on function public.provider_portal_availability_action(uuid,text,jsonb) from public,anon,authenticated;
grant execute on function public.provider_portal_availability_action(uuid,text,jsonb) to service_role;


-- Developer authorizes the service catalogue available to a Provider. Provider
-- may later pause/re-enable only rows that remain developer_authorized=true.
create or replace function public.developer_provider_service_action(
  p_actor uuid,
  p_provider_id uuid,
  p_service_ids jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare v_item jsonb; v_service uuid; v_names text[] := array[]::text[];
begin
  if not exists(select 1 from public.admin_portal_users where id=p_actor and active=true and role='DEVELOPER_ADMIN') then raise exception 'Unauthorized'; end if;
  if not exists(select 1 from public.providers where id=p_provider_id) then raise exception 'Provider not found'; end if;

  update public.provider_services
     set developer_authorized=false,provider_enabled=false,active=false,updated_at=now()
   where provider_id=p_provider_id;

  for v_item in select value from jsonb_array_elements(coalesce(p_service_ids,'[]'::jsonb)) loop
    begin v_service := trim(both '"' from v_item::text)::uuid;
    exception when others then raise exception 'Invalid service id'; end;
    if not exists(select 1 from public.services where id=v_service and active=true) then raise exception 'Service does not exist or is inactive'; end if;
    insert into public.provider_services(provider_id,service_id,active,developer_authorized,provider_enabled,updated_at)
    values(p_provider_id,v_service,true,true,true,now())
    on conflict(provider_id,service_id) do update set
      developer_authorized=true,
      provider_enabled=case when public.provider_services.developer_authorized=false then true else public.provider_services.provider_enabled end,
      active=case when public.provider_services.developer_authorized=false then true else public.provider_services.provider_enabled end,
      updated_at=now();
    v_names := array_append(v_names,(select name from public.services where id=v_service));
  end loop;

  insert into public.provider_technical_history(provider_id,event_type,event_label,details,actor_type,actor_admin_user_id)
  values(p_provider_id,'AUTHORIZED_SERVICES_CHANGED','Developer updated authorized services',jsonb_build_object('services',v_names),'DEVELOPER',p_actor);
  return jsonb_build_object('ok',true,'count',jsonb_array_length(coalesce(p_service_ids,'[]'::jsonb)));
end;
$$;
revoke all on function public.developer_provider_service_action(uuid,uuid,jsonb) from public,anon,authenticated;
grant execute on function public.developer_provider_service_action(uuid,uuid,jsonb) to service_role;

-- Provider self-service password changes are also recorded in the safe technical history.
create or replace function public.provider_portal_change_password(
  p_actor uuid,
  p_current_password text,
  p_new_password text
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare v_provider uuid;
begin
  if length(coalesce(p_new_password,'')) < 10 then raise exception 'New password must be at least 10 characters'; end if;
  update public.provider_portal_users u
     set password_hash=crypt(p_new_password,gen_salt('bf',12)),password_changed_at=now(),updated_at=now()
   where u.id=p_actor and u.active=true and u.password_hash=crypt(p_current_password,u.password_hash)
   returning provider_id into v_provider;
  if not found then raise exception 'Current password is incorrect'; end if;
  update public.provider_portal_sessions set revoked_at=now() where provider_user_id=p_actor and revoked_at is null;
  insert into public.provider_technical_history(provider_id,event_type,event_label,actor_type,actor_provider_user_id)
  values(v_provider,'PASSWORD_CHANGED','Provider changed portal password','PROVIDER',p_actor);
end;
$$;
revoke all on function public.provider_portal_change_password(uuid,text,text) from public,anon,authenticated;
grant execute on function public.provider_portal_change_password(uuid,text,text) to service_role;

